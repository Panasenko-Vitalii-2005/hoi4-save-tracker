import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const clientDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const definitionsPath = resolve(clientDirectory, "src/lib/equipmentNames.ts");
const outputPath = resolve(clientDirectory, "src/lib/equipmentCountryNames.generated.ts");

// The actual Logistics UI was verified to show this short label, unlike the
// default full-key label. Other _short keys are deliberately not used.
const VERIFIED_SHORT_KEYS = new Set(["JAP_anti_air_equipment_2"]);

export function readSupportedDefinitions(source) {
  const sourceFile = ts.createSourceFile(
    "equipmentNames.ts", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS,
  );
  const declaration = sourceFile.statements
    .filter(ts.isVariableStatement)
    .flatMap((statement) => [...statement.declarationList.declarations])
    .find((candidate) => candidate.name.getText(sourceFile) === "EQUIPMENT_DISPLAY_NAMES");
  const initializer = declaration?.initializer;
  const object = initializer && ts.isCallExpression(initializer)
    ? initializer.arguments[0]
    : null;
  if (!object || !ts.isObjectLiteralExpression(object)) {
    throw new Error("Could not find the EQUIPMENT_DISPLAY_NAMES object allowlist.");
  }

  const definitions = new Set();
  for (const property of object.properties) {
    if (!ts.isPropertyAssignment(property) ||
        !(ts.isIdentifier(property.name) || ts.isStringLiteral(property.name))) {
      throw new Error("Unsupported equipment definition declaration.");
    }
    definitions.add(property.name.text);
  }
  if (definitions.size === 0) throw new Error("Equipment definition allowlist is empty.");
  return definitions;
}

export function extractCountryEquipmentNames(
  localization, supportedDefinitions, verifiedShortKeys = VERIFIED_SHORT_KEYS,
) {
  if (!/^\uFEFF?l_english:\s*$/m.test(localization)) {
    throw new Error("Expected an official English equipment localization file.");
  }

  const fullNames = new Map();
  const shortNames = new Map();
  for (const [index, line] of localization.split(/\r?\n/).entries()) {
    const keyMatch = /^\s*([A-Z0-9]{3})_([a-z0-9_]+):/.exec(line);
    if (!keyMatch) continue;
    const [, tag, suffix] = keyMatch;
    const isShort = suffix.endsWith("_short");
    const definition = isShort ? suffix.slice(0, -"_short".length) : suffix;
    if (!supportedDefinitions.has(definition)) continue;
    const key = `${tag}_${definition}`;
    if (isShort && !verifiedShortKeys.has(key)) continue;

    // Paradox localization can contain literal quotes inside a quoted value
    // (for example the German armored-car name containing "Puma").
    const valueMatch = /^\s*[A-Z0-9]{3}_[a-z0-9_]+:(?:\d+)?\s*"(.*)"\s*(?:#.*)?$/.exec(line);
    if (!valueMatch) {
      throw new Error(`Invalid equipment localization value at line ${index + 1}.`);
    }
    const name = valueMatch[1]
      .replace(/\\n/g, "\n")
      .replace(/\\"/g, '"')
      .replace(/\\\\/g, "\\");
    if (typeof name !== "string" || !name.trim()) {
      throw new Error(`Empty equipment localization value at line ${index + 1}.`);
    }
    const target = isShort ? shortNames : fullNames;
    if (target.has(key)) throw new Error(`Duplicate equipment localization key: ${key}`);
    target.set(key, name);
  }

  for (const key of verifiedShortKeys) {
    if (!fullNames.has(key) || !shortNames.has(key)) {
      throw new Error(`Missing verified full/short equipment localization: ${key}`);
    }
    fullNames.set(key, shortNames.get(key));
  }
  if (fullNames.size === 0) throw new Error("No supported country equipment names found.");
  return new Map([...fullNames].sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0
  ));
}

export function renderCountryEquipmentNames(names, sourceHash) {
  const sortedNames = [...names].sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0
  );
  const entries = sortedNames.map(([key, name]) =>
    `  ${JSON.stringify(key)}: ${JSON.stringify(name)},`
  );
  return [
    "// Generated by client/scripts/generate-equipment-names.mjs. Do not edit manually.",
    "// Source: official HoI4 English equipment localization, filtered to the",
    "// EQUIPMENT_DISPLAY_NAMES allowlist. JAP anti-air II uses its verified UI short key.",
    `// Source SHA-256: ${sourceHash}`,
    `// Country-specific entries: ${sortedNames.length}`,
    "export const COUNTRY_EQUIPMENT_NAMES: Readonly<Record<string, string>> = Object.freeze({",
    ...entries,
    "});",
    "",
  ].join("\n");
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const paths = args.filter((arg) => arg !== "--check");
  if (paths.length !== 1) {
    throw new Error("Usage: node scripts/generate-equipment-names.mjs <equipment_l_english.yml> [--check]");
  }
  const [definitionsSource, localization] = await Promise.all([
    readFile(definitionsPath, "utf8"),
    readFile(paths[0], "utf8"),
  ]);
  const names = extractCountryEquipmentNames(
    localization, readSupportedDefinitions(definitionsSource),
  );
  const sourceHash = createHash("sha256").update(localization).digest("hex");
  const generated = renderCountryEquipmentNames(names, sourceHash);
  if (check) {
    if (await readFile(outputPath, "utf8") !== generated) {
      throw new Error("Generated country equipment names are out of date.");
    }
  } else {
    await writeFile(outputPath, generated, "utf8");
  }
  process.stdout.write(`${check ? "Verified" : "Generated"} ${names.size} country equipment names.\n`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
